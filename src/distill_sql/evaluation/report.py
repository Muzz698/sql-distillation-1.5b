"""Build results/README.md: one leaderboard per eval set, from the committed result files."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from distill_sql.config import AppConfig
from distill_sql.evaluation.metrics import mcnemar
from distill_sql.utils.io import iter_jsonl, read_json

BASELINE = "base-q8"


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{100 * x:.1f}"


def _num(x: float | None, fmt: str) -> str:
    return "-" if x is None else format(x, fmt)


def _significance(set_dir: Path, model: str) -> str:
    """Paired McNemar test vs the base model on the questions both have scored."""
    if model == BASELINE or not (set_dir / BASELINE / "scores.jsonl").exists():
        return ""
    base = {r["uid"]: r["ex"] for r in iter_jsonl(set_dir / BASELINE / "scores.jsonl")}
    mine = {r["uid"]: r["ex"] for r in iter_jsonl(set_dir / model / "scores.jsonl")}
    shared = sorted(base.keys() & mine.keys())
    if not shared:
        return ""
    a_only, b_only, p = mcnemar([mine[u] for u in shared], [base[u] for u in shared])
    return f"+{a_only}/-{b_only}, p={p:.3g}"


def render(cfg: AppConfig) -> str:
    assert cfg.evaluation is not None
    ev = cfg.evaluation
    out = [
        "# Evaluation results",
        "",
        "Generated by `make eval-report` from the files in this folder. EX = execution accuracy "
        "(main metric), EM = Spider exact-set match, Valid = prediction runs without error. "
        "95% CIs are bootstrap intervals. *vs base* is a paired McNemar test on the same "
        "questions: +questions only this model solves / -questions only the base model solves.",
        "",
        "Cost per 1,000 queries uses each provider's paid list price (we pay $0 on free tiers); "
        "local models are $0 marginal cost. Latency for teachers includes network time.",
        "",
    ]
    for set_name, spec in ev.sets.items():
        set_dir = ev.results_dir / set_name
        models = sorted(p.parent.name for p in set_dir.glob("*/metrics.json"))
        if not models:
            continue
        out += [
            f"## {set_name}",
            "",
            f"{spec.dataset} / {spec.split}"
            + (f", stratified subset of {spec.n}" if spec.n else ""),
            "",
            "| Model | EX % (95% CI) | EM % | Valid % | vs base | p50 latency | tok/s "
            "| Peak mem | $ / 1k q | Scored |",
            "|---|---|---:|---:|---|---:|---:|---:|---:|---:|",
        ]
        metrics: dict[str, dict[str, Any]] = {
            m: read_json(set_dir / m / "metrics.json") for m in models
        }
        for m in sorted(models, key=lambda k: -(metrics[k]["ex"] or 0)):
            r = metrics[m]
            ci = r["ex_ci95"]
            ex = f"{_pct(r['ex'])} ({_pct(ci[0])}-{_pct(ci[1])})" if ci else _pct(r["ex"])
            mem = f"{r['peak_memory_mb']:,} MB" if r.get("peak_memory_mb") else "-"
            cost = "-" if r["cost_per_1k_usd"] is None else f"${r['cost_per_1k_usd']:.3f}"
            scored = f"{r['n']}/{r['n_total']}" + ("" if r["complete"] else " (partial)")
            # Throughput is only meaningful for local models (API latency includes network).
            tok_s = _num(r["tokens_per_s"], ".0f") if r.get("kind") == "local" else "-"
            out.append(
                f"| {m} | {ex} | {_pct(r['em'])} | {_pct(r['valid_rate'])} "
                f"| {_significance(set_dir, m)} | {_num(r['latency_p50_s'], '.2f')} s "
                f"| {tok_s} | {mem} | {cost} | {scored} |"
            )
        levels = list(next(iter(metrics.values()))["by_difficulty"])
        out += ["", "EX % by difficulty:", "", "| Model | " + " | ".join(levels) + " |"]
        out.append("|---|" + "---:|" * len(levels))
        for m in models:
            bd = metrics[m]["by_difficulty"]
            cells = [
                f"{_pct(bd[lvl]['ex'])} (n={bd[lvl]['n']})" if lvl in bd else "-" for lvl in levels
            ]
            out.append(f"| {m} | " + " | ".join(cells) + " |")
        out.append("")
    out += [
        "---",
        "",
        "Data: Spider (Yu et al., 2018) and BIRD Mini-Dev (Li et al., 2023), both CC BY-SA 4.0. "
        "The questions and gold SQL inside the prediction files are derived from them and keep "
        "that license.",
    ]
    return "\n".join(out) + "\n"
